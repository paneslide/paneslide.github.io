// Precompute levels 1..N into js/levels.js. Usage: node tools/build-levels.js [300]
const E = require("../js/engine.js"), fs = require("fs");
const N = +process.argv[2] || 300, out = [];
const t0 = Date.now(); let slow = 0;
for (let i = 1; i <= N; i++) {
  const s = Date.now(), l = E.generateLevel(i);
  slow = Math.max(slow, Date.now() - s);
  if (l.fallback) console.log("level", i, "used fallback", l.fallback);
  out.push(E.packLevel(l));
}
fs.writeFileSync(__dirname + "/../js/levels.js", "/* PaneSlide precomputed levels 1-" + N + " (generated by tools/build-levels.js). */\nwindow.PANESLIDE_LEVELS=" + JSON.stringify(out) + ";\n");
console.log(`built ${N} levels in ${Date.now() - t0} ms (slowest ${slow} ms)`);
